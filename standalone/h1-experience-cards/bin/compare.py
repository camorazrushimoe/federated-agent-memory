#!/usr/bin/env python3
"""compare.py — build MODEL-MATRIX.md from run dirs. No hand-typed numbers.

Usage (from the h1 folder root):
  python bin/compare.py runs/ > MODEL-MATRIX.md

One row per extract model that has a stage-S2 measured run (the pro-model S0
portability run is explicitly NOT a measured arm and must not appear).
Columns (EVAL-PLAN §8): unlock_hit_label, wrong, abstain, serve_rate,
cluster_purity, reject_rate, judge faithful, USD/1000, p50 latency, verdict.

Verdict is taken from the run's report.md (§6.4 line: FIT / FIT WITH LIMITS /
NOT FIT). Ends with the literal "add an arm in three steps" block
(DELIVERABLE-PACKAGE.md §6).
"""

import argparse
import json
import os
import re
import sys


def read_json(path, default=None):
    if not os.path.exists(path):
        return default
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def pct(x, nd=3):
    try:
        return f"{float(x):.{nd}f}"
    except (TypeError, ValueError):
        return "—"


def verdict_from_report(report_path):
    if not os.path.exists(report_path):
        return "—"
    text = open(report_path, "r", encoding="utf-8").read()
    for line in text.splitlines():
        s = line.strip()
        for v in ("FIT WITH LIMITS", "NOT FIT"):
            if s.startswith(v) or f"**{v}**" in s:
                return v
        if re.search(r"\bFIT\b", s) and "FIT WITH LIMITS" not in s \
                and "NOT FIT" not in s:
            return "FIT"
    return "—"


def main():
    ap = argparse.ArgumentParser(description="Build MODEL-MATRIX.md from runs")
    ap.add_argument("runs_dir", nargs="?", default="runs")
    args = ap.parse_args()

    rows = []
    if not os.path.isdir(args.runs_dir):
        sys.exit(f"no runs dir: {args.runs_dir}")
    # Baseline arms may live in their own run dirs (RUN-PROTOCOL §1: one
    # invocation per --baseline). Collect per model: the T run + its B0/B1/B2.
    by_model = {}
    for name in sorted(os.listdir(args.runs_dir)):
        d = os.path.join(args.runs_dir, name)
        manifest = read_json(os.path.join(d, "manifest.json"))
        metrics = read_json(os.path.join(d, "metrics.json"))
        if not manifest or not metrics:
            continue
        if manifest.get("stage") != "S2":
            continue  # only measured S2 runs; portability S0 evidence excluded
        model = manifest.get("extract_model") or name
        arm = metrics.get("arm") or "T"
        by_model.setdefault(model, {})[arm] = (name, d, metrics)

    for model in sorted(by_model):
        t = by_model[model].get("T")
        if not t:
            continue
        _name, d, metrics = t
        primary = metrics.get("primary") or {}
        secondary = metrics.get("secondary") or {}
        cost = read_json(os.path.join(d, "cost.json")) or {}
        extract_cost = cost.get("extract") or {}
        usd_1000 = extract_cost.get("usd_per_1000_dialogues")
        usd_1000_s = (f"{float(usd_1000):.4f}"
                      if isinstance(usd_1000, (int, float)) else "null")
        rows.append({
            "model": model,
            "run": _name,
            "unlock_hit_label": pct(primary.get("unlock_hit_label")),
            "wrong": pct(primary.get("wrong")),
            "abstain": pct(primary.get("abstain")),
            "serve_rate": pct(secondary.get("serve_rate")),
            "cluster_purity": pct(secondary.get("cluster_purity")),
            "reject_rate": pct(secondary.get("reject_rate")),
            "judge_faithful": "—",
            "usd_1000": usd_1000_s,
            "p50_ms": extract_cost.get("ms_p50", "—"),
            "verdict": verdict_from_report(os.path.join(d, "report.md")),
        })

    out = []
    out.append("# MODEL-MATRIX — H1 experience cards\n")
    out.append("Generated by `bin/compare.py` from the run dirs — no "
               "hand-typed")
    out.append("numbers. One row per measured (stage S2) extract model.\n")
    out.append("| model | unlock_hit_label | wrong | abstain | serve_rate | "
               "cluster_purity | reject_rate | judge faithful | USD/1000 | "
               "p50 ms | verdict |")
    out.append("|--|--|--|--|--|--|--|--|--|--|--|")
    for r in rows:
        out.append("| {model} | {unlock_hit_label} | {wrong} | {abstain} | "
                   "{serve_rate} | {cluster_purity} | {reject_rate} | "
                   "{judge_faithful} | {usd_1000} | {p50_ms} | {verdict} |"
                   .format(**r))
    if not rows:
        out.append("| _(no measured S2 run yet)_ | | | | | | | | | | |")
    out.append("")
    out.append("## Add an arm in three steps")
    out.append("")
    out.append("```")
    out.append("1. python bin/run_experiment.py --stage S2 --model "
               "<new-model> --out runs/<date>_S2_<model>")
    out.append("2. python bin/compare.py runs/*/ > MODEL-MATRIX.md")
    out.append("3. read the new row next to B1 — if the new arm is at or "
               "below B1, the cards")
    out.append("   add nothing on that model, and that is the finding")
    out.append("```")
    out.append("")
    print("\n".join(out))


if __name__ == "__main__":
    main()
