#!/usr/bin/env python3
"""compare.py — MODEL-MATRIX.md generator (EVAL-PLAN §8, DELIVERABLE-PACKAGE §6).

    python bin/compare.py > MODEL-MATRIX.md
    python bin/compare.py runs/*/ > MODEL-MATRIX.md

Reads metrics.json + cost.json (+ manifest.json, report.md) from every run
directory and renders the model matrix. NO hand-typed numbers: every cell is
read from a run dir, and the file ends with the literal "add an arm in three
steps" block so a stranger knows how to extend the experiment.

Inclusion rule: a run dir participates only if it is a MEASURED arm — stage
S2 per the manifest (EVAL-PLAN §9). The S0 portability proof (a different
model id with no code edit) is deliberately EXCLUDED: it is evidence of
portability, not a measured arm, and must never get a matrix row
(DELIVERABLE-PACKAGE §6, LAB-BRIEF §3 addendum).

Exit code: 0 on success. A run dir with a missing metrics.json or cost.json
is skipped with a warning to stderr (never guessed).
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

COLUMNS = ["unlock_hit_label", "wrong", "abstain", "serve_rate",
           "cluster_purity", "reject_rate", "judge_faithful",
           "usd_per_1000", "ms_p50", "verdict"]

VERDICT_FORMS = ("FIT", "FIT WITH LIMITS", "NOT FIT")


def load_json(path: Path) -> dict | None:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as e:
        print(f"compare: WARN skipping {path}: {e}", file=sys.stderr)
        return None


def verdict_from_report(report_md: str) -> str | None:
    """Last line containing exactly one of the three EVAL-PLAN §6.4 verdict forms."""
    last = None
    for line in report_md.splitlines():
        for form in VERDICT_FORMS:
            if re.search(rf"\b{re.escape(form)}\b", line):
                last = form
    return last


def row_for(run_dir: Path) -> dict | None:
    manifest = load_json(run_dir / "manifest.json") or {}
    metrics = load_json(run_dir / "metrics.json")
    cost = load_json(run_dir / "cost.json")
    if metrics is None or cost is None:
        return None

    stage = manifest.get("stage")
    if stage != "S2":
        return None  # measured arms only (S0/S1 dev runs, S0 portability proof)

    model = manifest.get("extract_model") or "unknown"
    prim = metrics.get("primary", {})
    sec = metrics.get("secondary", {})
    judge = metrics.get("judge") or {}
    extract_cost = cost.get("extract", {})

    report = run_dir / "report.md"
    verdict = (metrics.get("verdict")
               or (verdict_from_report(report.read_text(encoding="utf-8"))
                   if report.exists() else None)
               or "no verdict")

    return {
        "model": model,
        "run_id": manifest.get("run_id") or run_dir.name,
        "unlock_hit_label": prim.get("unlock_hit_label"),
        "wrong": prim.get("wrong"),
        "abstain": prim.get("abstain"),
        "serve_rate": sec.get("serve_rate"),
        "cluster_purity": sec.get("cluster_purity"),
        "reject_rate": sec.get("reject_rate"),
        "judge_faithful": judge.get("faithful"),
        "usd_per_1000": extract_cost.get("usd_per_1000_dialogues"),
        "ms_p50": extract_cost.get("ms_p50"),
        "verdict": verdict,
    }


def fmt(v, default="—") -> str:
    if v is None:
        return default
    if isinstance(v, float):
        return f"{v:.4f}"
    return str(v)


def render(rows: list[dict]) -> str:
    lines = []
    lines.append("# H1 Experience Cards — Model Matrix")
    lines.append("")
    lines.append("One row per **measured** extract model (stage S2). Generated by")
    lines.append("`bin/compare.py` from the run dirs — no hand-typed numbers.")
    lines.append("")
    lines.append("| model | unlock_hit_label | wrong | abstain | serve_rate | "
                 "cluster_purity | reject_rate | judge faithful | USD/1k | p50 ms | verdict |")
    lines.append("|--|--|--|--|--|--|--|--|--|--|--|")
    if not rows:
        lines.append("| _no measured S2 runs yet_ | | | | | | | | | | |")
    for r in rows:
        lines.append("| " + " | ".join([
            f"`{r['model']}`",
            fmt(r["unlock_hit_label"]),
            fmt(r["wrong"]),
            fmt(r["abstain"]),
            fmt(r["serve_rate"]),
            fmt(r["cluster_purity"]),
            fmt(r["reject_rate"]),
            fmt(r["judge_faithful"]),
            fmt(r["usd_per_1000"], "null"),
            fmt(r["ms_p50"]),
            r["verdict"],
        ]) + " |")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("## Add an arm in three steps")
    lines.append("")
    lines.append("```")
    lines.append("1. python bin/run_experiment.py --stage S2 --model <new-model> --out runs/<date>_S2_<model>")
    lines.append("2. python bin/compare.py runs/*/ > MODEL-MATRIX.md")
    lines.append("3. read the new row next to B1 — if the new arm is at or below B1, the cards")
    lines.append("   add nothing on that model, and that is the finding")
    lines.append("```")
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    args = argv if argv is not None else sys.argv[1:]
    if args:
        run_dirs = [Path(a) for a in args]
    else:
        run_dirs = sorted((ROOT / "runs").glob("*/")) if (ROOT / "runs").exists() else []
    rows = []
    for d in run_dirs:
        if not d.is_dir():
            continue
        r = row_for(d)
        if r is not None:
            rows.append(r)
    # deterministic: by model then run_id
    rows.sort(key=lambda r: (r["model"], r["run_id"]))
    sys.stdout.write(render(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main())
